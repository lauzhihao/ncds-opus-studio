// 把内核拼成给 draft 阶段用的"写作宪法"文本,注入 douyin_cog profile 的 prompt。
export function buildKernelGuide() {
  const lines = [];
  lines.push('你是「柳永」——一个研究"如何用文字让人停下来看完并行动"的抖音爆款编剧。');
  lines.push('下面是从真实爆款离线蒸馏的判断力,你必须严格遵守,这是你区别于"普通 AI 写手"的全部秘密。');
  lines.push('');
  lines.push('== 通用母规律(必须条条命中) ==');
  UNIVERSAL_LAWS.forEach((l, i) => lines.push(`${i + 1}. ${l}`));
  lines.push('');
  lines.push('== 认知爆款骨架(按这四段写) ==');
  COGNITION_SKELETON.forEach((s) => lines.push(`${s.seg}:${s.do}(目的:${s.why};示例:${s.example})`));
  lines.push('');
  lines.push('== 认知赛道专属打法 ==');
  lines.push(`钩子:${COGNITION_PLAYBOOK.hook}`);
  lines.push(`信任:${COGNITION_PLAYBOOK.trust}`);
  lines.push(`方法:${COGNITION_PLAYBOOK.method}`);
  lines.push(`情绪:${COGNITION_PLAYBOOK.emotion}`);
  lines.push('');
  lines.push('== 范例(学它们的钩子和结构,不要照抄内容) ==');
  EXEMPLARS.forEach((e) => lines.push(`[${e.likes}]《${e.title}》钩子:${e.hook};机制:${e.mechanism};打法:${e.tactics}`));
  lines.push('');
  lines.push('== 硬性禁止(这些是别人翻过的车,你绝不能犯) ==');
  ANTI_PATTERNS.forEach((a, i) => lines.push(`${i + 1}. ${a}`));
  return lines.join('\n');
}

export const COGNITION_KERNEL = {
  UNIVERSAL_LAWS, COGNITION_SKELETON, COGNITION_PLAYBOOK, TOPIC_FORMULA, EXEMPLARS, ANTI_PATTERNS,
};
